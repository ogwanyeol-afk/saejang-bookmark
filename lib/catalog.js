/** stagesFor(profile 또는 form) → 그 이용자의 단계 목록 */
export function stagesFor(x) {
  const persona = typeof x === 'object' ? (x?.persona || x?.form) : x;
  if (LIFE_STAGES[persona]) return LIFE_STAGES[persona];
  const form = typeof x === 'object' ? x?.form : x;
  if (form === 'corp') return STAGES_CORP;
  if (form === 'pre') return [PRE_STAGE, ...STAGES_INDIV.slice(1)];
  return STAGES_INDIV;
}

